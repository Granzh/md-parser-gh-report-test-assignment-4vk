bool in_ranges(const std::vector<CodeRange>& table, char32_t cp) noexcept {  // NOLINT(contract) see header
    auto it = std::upper_bound(table.begin(), table.end(), cp,
                               [](char32_t value, const CodeRange& range) { return value < range.first; });
    return it != table.begin() && cp <= (it - 1)->last;
}

