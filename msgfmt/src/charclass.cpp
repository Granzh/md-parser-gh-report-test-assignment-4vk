bool is_whitespace(char32_t cp) noexcept {  // NOLINT(contract) documented in charclass.hpp
    return (cp >= 0x0009 && cp <= 0x000D) || cp == 0x0020 || cp == 0x0085 || cp == 0x00A0 || cp == 0x1680 ||
           (cp >= 0x2000 && cp <= 0x200A) || cp == 0x2028 || cp == 0x2029 || cp == 0x202F || cp == 0x205F ||
           cp == 0x3000;
}

bool is_letter_or_digit(char32_t cp) noexcept {  // NOLINT(contract) documented in charclass.hpp
    return detail::in_ranges(detail::letter_digit_table(), cp);
}

